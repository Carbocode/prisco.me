type CoreRingsProps = { rimGradientId: string; heatFilterId: string };

/** Bordo luminoso e calore degli anelli, per le pagine che non hanno già le defs della home. */
export function CoreRingsDefs({ rimGradientId, heatFilterId }: CoreRingsProps) {
  return (
    <defs>
      <linearGradient id={rimGradientId} x1="0" y1="0" x2=".2" y2="1">
        <stop stopColor={glow.rimTop} stopOpacity=".85" />
        <stop offset="1" stopColor={glow.rimBottom} stopOpacity=".08" />
      </linearGradient>
      <filter id={heatFilterId} x="-10%" y="-10%" width="120%" height="120%">
        <feDropShadow dy="-6" stdDeviation="10" floodColor={glow.heat} floodOpacity=".45" />
      </filter>
    </defs>
  );
}

export default function CoreRings({ rimGradientId, heatFilterId }: CoreRingsProps) {
  return (
    <g filter={`url(#${heatFilterId})`}>
      {rings.map((ring) => (
        <g
          key={ring.spin}
          className={ring.reverse ? "core-ring is-rev" : "core-ring"}
          style={{ "--spin": ring.spin }}
        >
          <path
            d={ring.d}
            fill={ring.fill}
            fillOpacity={ring.opacity}
            stroke={`url(#${rimGradientId})`}
            strokeWidth="2"
            vectorEffect="non-scaling-stroke"
          />
        </g>
      ))}
    </g>
  );
}
